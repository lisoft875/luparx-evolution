-- =============================================================================================
-- V19_0 — Costa Rica: el árbol territorial completo.
--
-- Hasta aquí la base traía sólo los distritos que alguna municipalidad de prueba necesitaba, así
-- que el formulario de dirección ofrecía una fracción del país y un vecino de Nicoya no podía
-- escribir dónde vive. Esto carga la División Territorial Administrativa: 7 provincias,
-- 84 cantones y 484 distritos.
--
-- Códigos: los oficiales, que son los que la base ya usaba — provincia '1', cantón '101',
-- distrito '10101'. Concatenados forman el código postal de cinco dígitos, que es lo que hace
-- que este árbol sirva para direcciones reales y no sólo para poblar un desplegable.
--
-- El padre se resuelve por código y no por identificador: así la migración se aplica igual sobre
-- una base que ya cargó parte del árbol por el back-office, y ON CONFLICT DO NOTHING deja intacto
-- lo que ya estuviera, incluidos los nombres oficiales de los cantones centrales.
--
-- Origen: paquete @juniorov/cr-locations (instantánea de 2020: 82 cantones, 482 distritos) más
-- los cantones Monteverde y Puerto Jiménez, creados en 2021 y 2022, tomados de la DTA 2026 del
-- Instituto Geográfico Nacional. La DTA vigente declara 494 distritos: los que falten son de
-- creación posterior a esa instantánea y se cargan por el endpoint de catálogo de plataforma,
-- sin necesidad de otra migración.
-- =============================================================================================

